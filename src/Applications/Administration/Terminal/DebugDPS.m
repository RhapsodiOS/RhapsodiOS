static void writeWord(unsigned char *bytes, unsigned int offset,
                      unsigned int value)
{
    bytes[offset] = (unsigned char)(value >> 24);
    bytes[offset + 1] = (unsigned char)(value >> 16);
    bytes[offset + 2] = (unsigned char)(value >> 8);
    bytes[offset + 3] = (unsigned char)value;
}

static void writeFloat(unsigned char *bytes, unsigned int offset, double value)
{
    union {
        float value;
        unsigned int bits;
    } representation;

    representation.value = (float)value;
    writeWord(bytes, offset, representation.bits);
}

void debugActivate(void)
{
    DPSBinObjSeqWrite(DPSGetCurrentContext(), activateSequence,
                      sizeof(activateSequence));
}

void debugDeactivate(int activeApp)
{
    unsigned char sequence[sizeof(deactivateSequence)];

    memcpy(sequence, deactivateSequence, sizeof(sequence));
    writeWord(sequence, 8, (unsigned int)activeApp);
    DPSBinObjSeqWrite(DPSGetCurrentContext(), sequence, sizeof(sequence));
}

void getActiveApp(int *activeApp)
{
    unsigned char sequence[sizeof(activeAppSequence)];

    memcpy(sequence, activeAppSequence, sizeof(sequence));
    writeWord(sequence, 16, (unsigned int)(uintptr_t)activeApp);
    DPSBinObjSeqWrite(DPSGetCurrentContext(), sequence, sizeof(sequence));
}

void TermCaret(double x, double y, double height)
{
    unsigned char sequence[sizeof(caretSequence)];

    memcpy(sequence, caretSequence, sizeof(sequence));
    writeFloat(sequence, 40, x);
    writeFloat(sequence, 48, y);
    writeFloat(sequence, 72, height);
    DPSBinObjSeqWrite(DPSGetCurrentContext(), sequence,
                      sizeof(sequence) - 1);
}

void TermUnderline(double x, double y, double width)
{
    unsigned char sequence[sizeof(underlineSequence)];

    memcpy(sequence, underlineSequence, sizeof(sequence));
    writeFloat(sequence, 8, x);
    writeFloat(sequence, 16, y);
    writeFloat(sequence, 32, width);
    DPSBinObjSeqWrite(DPSGetCurrentContext(), sequence, sizeof(sequence));
}
