/*
 * efi_vga.c -- Put the VGA card back into standard text mode 3 before the
 * jump to the kernel.
 *
 * Why this exists: there is no BIOS int 10h under UEFI. Booted the legacy
 * way, SeaBIOS/boot1 leave the card (QEMU -vga cirrus) in plain VGA mode 3
 * (80x25 text) with a working character-generator font; booted by this
 * loader, OVMF's GOP driver leaves the same physical card in a GOP/SVGA
 * graphics mode instead. Investigation of src/kernel-7/bsd/dev/i386/
 * VGAConsole.c (VGASetGraphicsMode(), reached from BasicConsole.c and
 * km.m's kminit() via kernBootStruct->graphicsMode) shows the kernel's own
 * console driver fully reprograms the Sequencer/CRTC/Graphics Controller/
 * Attribute Controller registers itself, via direct port I/O, into VGA
 * mode 0x12 (640x480, 16-colour planar) -- it never uses text mode or
 * 0xB8000, and never reads the character-generator font this file loads
 * (it blits its own compiled-in font, ohlfs12, straight into plane
 * memory). What the kernel's from-scratch register programming does
 * depend on is the card actually behaving like standard VGA hardware --
 * legacy 0xA0000-0xBFFFF aperture decoding and register semantics -- which
 * is exactly what SeaBIOS's mode-3 state guarantees and what an
 * OVMF/GOP SVGA mode is not guaranteed to leave intact. This routine
 * restores that known-good hardware state (matching the proven-working
 * BIOS path) using only direct port and memory I/O, none of which needs
 * boot services.
 *
 * The character-generator font reload is not on the kernel's own console
 * path (see above) but is cheap, restores a genuinely complete mode-3
 * state, and is included for exactly the reason a text-shaped-garbage
 * screen would otherwise be hard to tell apart from a register-programming
 * mistake.
 */

static inline void outb(unsigned short port, unsigned char val)
{
    __asm__ volatile("outb %0, %1" : : "a"(val), "Nd"(port));
}

static inline unsigned char inb(unsigned short port)
{
    unsigned char val;
    __asm__ volatile("inb %1, %0" : "=a"(val) : "Nd"(port));
    return val;
}

