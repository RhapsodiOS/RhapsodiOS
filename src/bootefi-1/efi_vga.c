static const unsigned char blank_glyph[8] = {0,0,0,0,0,0,0,0};

static void load_font(void)
{
    unsigned i, r;
    volatile unsigned char *fb = (volatile unsigned char *)0xA0000;

    /* Switch to plane 2 only, sequential (non odd/even) addressing so
     * plane 2 -- the character generator plane -- is linearly
     * addressable at 0xA0000. */
    outb(SEQ_ADDR, 0x00); outb(SEQ_DATA, 0x01); /* synchronous reset   */
    outb(SEQ_ADDR, 0x02); outb(SEQ_DATA, 0x04); /* map mask: plane 2   */
    outb(SEQ_ADDR, 0x04); outb(SEQ_DATA, 0x07); /* sequential, ext mem */
    outb(SEQ_ADDR, 0x00); outb(SEQ_DATA, 0x03); /* clear reset         */

    outb(GC_ADDR, 0x04); outb(GC_DATA, 0x02); /* read from plane 2       */
    outb(GC_ADDR, 0x05); outb(GC_DATA, 0x00); /* write mode 0, read mode 0*/
    outb(GC_ADDR, 0x06); outb(GC_DATA, 0x00); /* map at 0xA0000, no o/e  */

    for (i = 0; i < 256; i++) {
        const unsigned char *glyph =
            (i >= 0x20 && i < 0x20 + 96) ? font8x8[i - 0x20] : blank_glyph;

        for (r = 0; r < 8; r++) {
            fb[i * 32 + r * 2]     = glyph[r];
            fb[i * 32 + r * 2 + 1] = glyph[r];
        }
    }

    /* Restore normal text-mode plane/addressing configuration. */
    outb(SEQ_ADDR, 0x00); outb(SEQ_DATA, 0x01);
    outb(SEQ_ADDR, 0x02); outb(SEQ_DATA, 0x03); /* planes 0+1 (char+attr) */
    outb(SEQ_ADDR, 0x04); outb(SEQ_DATA, 0x02); /* odd/even             */
    outb(SEQ_ADDR, 0x00); outb(SEQ_DATA, 0x03);

    outb(GC_ADDR, 0x04); outb(GC_DATA, 0x00);
    outb(GC_ADDR, 0x05); outb(GC_DATA, 0x10); /* odd/even mode           */
    outb(GC_ADDR, 0x06); outb(GC_DATA, 0x0E); /* map at 0xB8000, alpha   */
}

/*
 * Program the standard VGA registers for mode 3 (80x25, 16-colour text),
 * reload the character generator font, and clear the text buffer. Called
 * from efi_exit_and_start() (handoff.c) right before the jump to the
 * kernel -- direct port/memory I/O only, no boot services touched.
 */
void efi_vga_reset_text_mode(void)
{
    unsigned i;
    volatile unsigned short *text = (volatile unsigned short *)0xB8000;

    outb(MISC_OUTPUT, 0x67);

    for (i = 0; i < 5; i++) {
        outb(SEQ_ADDR, i);
        outb(SEQ_DATA, mode3_seq[i]);
    }

    /* QEMU's -vga cirrus model (the card this loader actually runs
     * against) is not just generic VGA: it has its own Extended
     * Sequencer Mode register (SR07, beyond the 5 standard sequencer
     * registers above) that, when set, routes every 0xA0000-0xBFFFF
     * access through a completely different Cirrus bank-switched
     * addressing scheme instead of the standard odd/even-and-memory-map
     * logic GR04/GR06 below configure -- OVMF's GOP driver sets this bit
     * for its own SVGA mode and nothing else ever clears it. Likewise
     * CR1B/CR1D hold extra high bits of the CRTC start address that
     * OVMF's higher-resolution mode needs (the standard CR0C/CR0D pair
     * is only 16 bits) and that a plain mode-3 CRTC table has no slot
     * for; left nonzero, the text renderer reads character/attribute
     * data from a garbage offset instead of offset 0, which is exactly
     * what a screen full of static noise (rather than blank or
     * corrected-looking text) looks like. Clearing all three is what
     * actually restores standard-VGA addressing on this card. */
    outb(SEQ_ADDR, 0x07);
    outb(SEQ_DATA, 0x00);

    /* CRTC registers 0-7 are write-protected by bit 7 of index 0x11;
     * clear it before writing the rest of the table. */
    outb(CRTC_ADDR, 0x11);
    outb(CRTC_DATA, 0x00);
    for (i = 0; i < 25; i++) {
        outb(CRTC_ADDR, i);
        outb(CRTC_DATA, mode3_crtc[i]);
    }
    outb(CRTC_ADDR, 0x1B); outb(CRTC_DATA, 0x00); /* Cirrus ext. start addr */
    outb(CRTC_ADDR, 0x1D); outb(CRTC_DATA, 0x00); /* Cirrus overlay ext.    */

    for (i = 0; i < 9; i++) {
        outb(GC_ADDR, i);
        outb(GC_DATA, mode3_gc[i]);
    }

    (void)inb(INPUT_STATUS1); /* reset attribute controller flip-flop to index */
    for (i = 0; i < 21; i++) {
        outb(AC_ADDR, i);
        outb(AC_DATA, mode3_ac[i]);
    }
    (void)inb(INPUT_STATUS1);
    outb(AC_ADDR, 0x20); /* re-enable video output */

    load_font();

    for (i = 0; i < 80 * 25; i++)
        text[i] = 0x0720; /* ' ' on a normal grey-on-black attribute */
}

