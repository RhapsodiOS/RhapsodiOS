int Ph_LoadSequencer(Adaptec2940HostInfo *host)
{
	unsigned short ioBase = (unsigned short)*(unsigned int *)(host->bytes + A2940_HA_IO_BASE_OFFSET);
	unsigned int mode = *(unsigned short *)(host->bytes + A2940_HA_MODE_OFFSET) == 2;
	unsigned char *presence = P_SeqExist + 12 * mode;
	unsigned short length = (unsigned short)(presence[0] | ((unsigned short)presence[1] << 8));
	unsigned int patchOffset;
	unsigned char patchByte;
	unsigned int i;

	if (length == 0)
		return -2;
	patchByte = (host->bytes[A2940_HA_OPTIONS_OFFSET] & 1) ? 0xff : 0xf0;
	patchOffset = *(unsigned int *)(presence + 8);
	if (patchOffset != 0)
		P_Seq_01[patchOffset] = patchByte;

	A2940_OUTB(ioBase + AIC_SEQCTL, 0x91);
	A2940_OUTB(ioBase + AIC_SEQADDR0, 0);
	A2940_OUTB(ioBase + AIC_SEQADDR1, 0);
	for (i = 0; i < length; ++i) {
		A2940_OUTB(ioBase + AIC_SEQRAM, P_Seq_01[i]);
	}
	A2940_OUTB(ioBase + AIC_SEQCTL, 0x90);
	A2940_OUTB(ioBase + AIC_SEQCTL, 0x91);
	A2940_OUTB(ioBase + AIC_SEQADDR0, 0);
	A2940_OUTB(ioBase + AIC_SEQADDR1, 0);
	for (i = 0; i < length; ++i) {
		if (A2940_INB(ioBase + AIC_SEQRAM) != P_Seq_01[i])
			return 255;
	}
	A2940_OUTB(ioBase + AIC_SEQCTL, 0x90);
	return 0;
}
