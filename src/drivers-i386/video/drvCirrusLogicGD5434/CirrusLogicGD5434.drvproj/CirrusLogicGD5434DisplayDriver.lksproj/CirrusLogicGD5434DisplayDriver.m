@implementation CirrusLogicGD5434DisplayDriver

/* Find the hardware, pick a mode and map the frame buffer. Every failure
 * after the superclass has initialized us returns whatever `[super free]'
 * returns.
 */
- initFromDeviceDescription:deviceDescription
{
    IODisplayInfo *displayInfo;
    int mode;

    if ([super initFromDeviceDescription:deviceDescription] == nil)
	return [super free];

    if ([self determineConfiguration] == NO)
	return [super free];

    if (busType == 1) {
	if ([self setPCIConfiguration] == NO)
	    return [super free];
    }

    mode = [self selectMode];
    if (mode >= 0 && [self setPendingDisplayMode:mode] == NO) {
	IOLog("%s: Selected mode not supported.\n", [self name]);
	mode = -1;
    }
    if (mode < 0) {
	IOLog("%s: Trying default mode.\n", [self name]);
	mode = defaultMode;
	if ([self setPendingDisplayMode:mode] == NO) {
	    IOLog("%s: Default mode not supported!\n", [self name]);
	    return [super free];
	}
    }

    physicalAddress = [deviceDescription memoryRangeList][0].start;
    vram = (void *)[self mapFrameBufferAtPhysicalAddress:physicalAddress
		    length:installedVRAMBytes];
    if (vram == 0) {
	IOLog("%s: Unable to map frame buffer\n", [self name]);
	return [super free];
    }

    blueTransferTable = 0;
    greenTransferTable = 0;
    redTransferTable = 0;
    transferTableCount = 0;
    brightnessLevel = EV_SCREEN_MAX_BRIGHTNESS;

    displayInfo = [self displayInfo];
    *displayInfo = modeTable[mode];
    displayInfo->frameBuffer = vram;
    if (displayInfo->bitsPerPixel == IO_8BitsPerPixel)
	displayInfo->flags = IO_DISPLAY_HAS_TRANSFER_TABLE;
    else
	displayInfo->flags = IO_DISPLAY_NEEDS_SOFTWARE_GAMMA_CORRECTION;
    currentMode = 0;

    return self;
}

/* Ask the superclass to pick the configured mode, telling it which entries
 * the installed memory can actually hold.
 */
- (int)selectMode
{
    BOOL valid[modeTableCount];
    int i, mode;

    for (i = 0; i < modeTableCount; i++) {
	valid[i] = (installedVRAMBytes >=
		    modeTable[i].rowBytes * modeTable[i].height);
    }

    mode = [self selectMode:modeTable count:modeTableCount valid:valid];
    if (mode < 0)
	IOLog("%s: Selected mode not supported.\n", [self name]);
    return mode;
}

/* Put the display into linear frame buffer mode. The screen is cleared
 * before the palette is loaded, so it is blanked rather than showing the
 * old palette against the new mode.
 */
- (void)enterLinearMode
{
    if (currentMode == 1)
	return;

    currentMode = 1;
    [self setMode:(const GD5434Mode *)[self displayInfo]->parameters];
    [self clearScreen];
    [self setGammaTable];
}

/* Get the device back into a state where it can be used as a standard VGA
 * device. The screen is cleared first, while the linear mapping is still
 * the one the frame buffer is programmed for.
 */
- (void)revertToVGAMode
{
    currentMode = 2;
    [self clearScreen];
    [self setMode:&vgaMode];
    [super revertToVGAMode];
}

/* Identify the chip, size its memory, choose a mode table and work out
 * which of its entries this card can display.
 */
- (BOOL)determineConfiguration
{
    const char *chipName;
    int i;

    /* Unlock the Cirrus extensions and read the key back. */
    outw(0x3C4, 0xFA06);
    if (inw(0x3C4) != 0x1206) {
	IOLog("%s: Cirrus Logic CL-GD543X or CL-GD5446 not found\n",
	      [self name]);
	return NO;
    }

    /* The chip is identified by the top six bits of CR27. */
    outb(0x3D4, 0x27);
    switch (inb(0x3D5) & 0xFC) {
    case 0xA0:
	chipType = 0;
	chipName = "Cirrus Logic GD5430";
	break;

    case 0xA8:
	chipType = 1;
	chipName = "Cirrus Logic GD5434";
	break;

    case 0xAC:
	chipType = 2;
	chipName = "Cirrus Logic GD5436";
	break;

    case 0xB8:
	chipType = 3;
	chipName = "Cirrus Logic GD5446";
	break;

    default:
	chipType = 4;
	chipName = "Unknown device";
	break;
    }

    if (chipType <= 1) {
	modeTable = GD5434_modeTable;
	modeTableCount = GD5434_modeTableCount;
	defaultMode = GD5434_defaultMode;
    } else if (chipType <= 4) {
	modeTable = GD5446_modeTable;
	modeTableCount = GD5446_modeTableCount;
	defaultMode = GD5446_defaultMode;
    }

    /* The low nibble of SR15 scales 256K. */
    outb(0x3C4, 0x15);
    installedVRAMBytes = 0x40000 << (inb(0x3C5) & 0x0F);

    IOLog("%s: %s detected (%d Bytes)\n", [self name], chipName,
	  installedVRAMBytes);

    if (strcmp([[[self deviceDescription] configTable]
		valueForStringKey:"Bus Type"], "PCI") == 0)
	busType = 1;
    else
	busType = 0;

    /* Work out what each mode costs and whether we can afford it. The two
     * tests are sequential, not exclusive: a large mode on a small card
     * takes the first flag and then has it replaced by the second.
     */
    for (i = 0; i < modeTableCount; i++) {
	modeTable[i].memorySize = modeTable[i].rowBytes * modeTable[i].height;
	modeTable[i].scanRate = 0;
	modeTable[i].screenWidth = 0;
	modeTable[i].screenHeight = 0;
	modeTable[i].modeUnavailableFlag = 0;

	if (modeTable[i].width > 1024 && installedVRAMBytes <= 0x1FFFFF)
	    modeTable[i].modeUnavailableFlag = IO_DISPLAY_MODE_OTHER_INVALID;
	if (installedVRAMBytes < modeTable[i].memorySize)
	    modeTable[i].modeUnavailableFlag =
		IO_DISPLAY_MODE_NEEDS_MORE_MEMORY;
    }
    return YES;
}

/* Reject a base address the BIOS left in the low eight megabytes, where
 * main memory lives.
 */
- (BOOL)isValidPCIAssignedBaseAddress:(unsigned int)address
{
    if (address > 0x7FFFFF)
	return YES;
    return NO;
}

/* Take the frame buffer base address from PCI configuration space and make
 * the device description agree with it.
 */
- (BOOL)setPCIConfiguration
{
    IOPCIConfigSpace configSpace;
    IORange range[3];
    unsigned char deviceNumber, functionNumber, busNumber;
    IOPCIDeviceDescription *deviceDescription;
    IORange *rangeList;
    int rangeCount;
    int i;

    deviceDescription = [self deviceDescription];

    if ([deviceDescription getPCIdevice:&deviceNumber
	 function:&functionNumber bus:&busNumber] != IO_R_SUCCESS) {
	IOLog("%s: unsupported PCI hardware.", [self name]);
	return NO;
    }
    IOLog("%s: PCI Dev: %d Func: %d Bus: %d\n", [self name],
	  deviceNumber, functionNumber, busNumber);

    [self getPCIConfigSpace:&configSpace];
    physicalAddress = configSpace.BaseAddress[0];
    physicalAddress &= ~0x0F;

    if ([self isValidPCIAssignedBaseAddress:physicalAddress]) {
	rangeList = [deviceDescription memoryRangeList];
	rangeCount = [deviceDescription numMemoryRanges];
	if (rangeCount != 3) {
	    IOLog("%s: Incorrect number of address ranges: %d.\n",
		  [self name], rangeCount);
	    return NO;
	}

	for (i = 0; i < rangeCount; i++)
	    range[i] = rangeList[i];
	range[0].start = physicalAddress;
	if ([deviceDescription setMemoryRangeList:range num:3] ==
	    IO_R_SUCCESS)
	    return YES;

	IOLog("%s: Can't set memory range, using default.\n", [self name]);

	/* Go back to the ranges the BIOS assigned and adopt the base
	 * address we were trying to replace.
	 */
	for (i = 0; i < rangeCount; i++)
	    range[i] = rangeList[i];
	physicalAddress = range[0].start;
	if ([deviceDescription setMemoryRangeList:range num:3] ==
	    IO_R_SUCCESS)
	    return YES;

	IOLog("%s: Can't set to default range either!\n", [self name]);
	return NO;
    }

    /* The assigned base address is unusable, so tell the card about the
     * one the device description already has.
     */
    physicalAddress = [deviceDescription memoryRangeList][0].start;
    configSpace.BaseAddress[0] = physicalAddress;
    [self setPCIConfigSpace:&configSpace];
    return YES;
}

/* Program the register set for one mode. The order of these writes is
 * load-bearing and must not be rearranged.
 */
- (void)setMode:(const GD5434Mode *)mode
{
    unsigned char value;
    int i;

    /* Clear the palette address source: video off. */
    inb(0x3DA);
    outb(0x3C0, 0x00);

    /* SR01 - SR04, then end the sequencer reset. */
    for (i = 1; i <= 4; i++)
	outw(0x3C4, (mode->seq[i - 1] << 8) | i);
    outw(0x3C4, 0x0300);

    outb(0x3C2, mode->misc);

    /* CR00 - CR07 are write protected until CR11 bit 7 is clear. */
    outb(0x3D4, 0x11);
    value = inb(0x3D5);
    outb(0x3D5, value & 0x7F);

    /* CR00 - CR18. */
    for (i = 0; i <= 24; i++)
	outw(0x3D4, (mode->crtc[i] << 8) | i);

    /* AR00 - AR14. */
    inb(0x3DA);
    for (i = 0; i <= 20; i++) {
	outb(0x3C0, i);
	outb(0x3C0, mode->attr[i]);
    }

    /* GR00 - GR08. */
    for (i = 0; i <= 8; i++)
	outw(0x3CE, (mode->gfx[i] << 8) | i);

    /* The VCLK numerator and denominator pairs, the same for every mode.
     * The mode picks one of them through the misc output and SR0E.
     */
    outw(0x3C4, 0x4A0B);
    outw(0x3C4, 0x2B1B);
    outw(0x3C4, 0x5B0C);
    outw(0x3C4, 0x2F1C);
    outw(0x3C4, 0x420D);
    outw(0x3C4, 0x1F1D);

    outw(0x3C4, (mode->seq07 << 8) | 0x07);

    outb(0x3C4, 0x0F);
    value = inb(0x3C5);
    outb(0x3C5, (value & 0x9F) | mode->seq0F);

    if (mode->seq0E != 0) {
	outw(0x3C4, (mode->seq0E << 8) | 0x0E);
	outw(0x3C4, (mode->seq1E << 8) | 0x1E);
    }

    outb(0x3CE, 0x0B);
    value = inb(0x3CF);
    outb(0x3CF, (value & 0xC0) | mode->gfx0B);

    outw(0x3D4, (mode->crtc1A << 8) | 0x1A);
    outw(0x3D4, (mode->crtc1B << 8) | 0x1B);

    /* SR16 takes one of two values depending on SR0F bit 2. */
    outb(0x3C4, 0x0F);
    if (inb(0x3C5) & 0x04) {
	outb(0x3C4, 0x16);
	outb(0x3C5, (inb(0x3C5) & 0xF0) | (mode->seq16WhenSet & 0x0F));
    } else {
	outb(0x3C4, 0x16);
	outb(0x3C5, (inb(0x3C5) & 0xF0) | (mode->seq16WhenClear & 0x0F));
    }

    /* The hidden DAC register is reached by reading the PEL mask four
     * times running and then writing it. The reads have no result but
     * they must all happen, and nothing may come between them.
     */
    outb(0x3C6, 0x00);
    inb(0x3C6);
    inb(0x3C6);
    inb(0x3C6);
    inb(0x3C6);
    outb(0x3C6, mode->hiddenDAC);
    outb(0x3C6, 0xFF);

    outb(0x3C4, 0x17);
    value = inb(0x3C5);
    outb(0x3C5, value & 0xFB);

    /* Reset the drawing engine and the cursor and overlay registers, and
     * turn the extended write mode off.
     */
    outw(0x3CE, 0x000F);
    outw(0x3D4, 0x001C);
    outw(0x3D4, 0x001D);
    outw(0x3C4, 0x0010);
    outw(0x3C4, 0x0011);
    outw(0x3C4, 0x0012);
    outw(0x3C4, 0x0013);
    outw(0x3CE, 0x0009);
    outw(0x3CE, 0x000A);
    outb(0x3CE, 0x0B);
    value = inb(0x3CF);
    outb(0x3CF, value & 0xFE);

    if (mode->seq0E != 0) {
	outb(0x3C4, 0x07);
	value = inb(0x3C5);
	outb(0x3C5, value | 0x10);
    }

    /* Set the palette address source: video on. */
    inb(0x3DA);
    outb(0x3C0, 0x20);

    /* Clear the sequencer's screen off bit: unblank. */
    outb(0x3C4, 0x01);
    value = inb(0x3C5);
    outb(0x3C5, value & 0xDF);
}

/* Zero the whole mapped aperture, not just the visible frame.
 */
- (void)clearScreen
{
    bzero(vram, installedVRAMBytes);
}

- (const char *)name
{
    const char *name;

    name = [super name];
    return (name == 0 || *name == '\0')
	? "CirrusLogicGD5434DisplayDriver" : name;
}

/* Refuse a mode this card cannot hold. The memory test repeats the one
 * `determineConfiguration' made, because this can be reached without it
 * having run again.
 */
- (BOOL)setPendingDisplayMode:(int)mode
{
    if (mode < 0 || mode >= modeTableCount)
	return NO;
    if (modeTable[mode].memorySize > installedVRAMBytes)
	return NO;
    if (modeTable[mode].width > 1024 && installedVRAMBytes <= 0x1FFFFF)
	return NO;
    if ([super setPendingDisplayMode:mode] == NO)
	return NO;
    return YES;
}

- (unsigned int)displayModeCount
{
    return modeTableCount;
}

- (IODisplayInfo *)displayModes
{
    return modeTable;
}

- (unsigned int)displayMemorySize
{
    return installedVRAMBytes;
}

